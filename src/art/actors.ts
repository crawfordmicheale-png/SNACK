function drawSlime(p: Painter, frame: number): void {
  // Squash-and-stretch hop.
  const squash = [0, 1, 2, 1][frame];
  const h = 9 - squash;
  const w = 6 + squash;
  const y = 15 - h;
  p.ellipse(8, y + h / 2, w, h / 2, PAL.slimeDark);
  p.ellipse(8, y + h / 2 + 0.5, w - 1.5, h / 2 - 1, PAL.slime);
  p.ellipse(6, y + 2, 2, 1.4, PAL.slimeLight);
  p.rect(6, y + 3, 2, 2, PAL.black);
  p.rect(10, y + 3, 2, 2, PAL.black);
  p.px(6, y + 3, PAL.white);
  p.px(10, y + 3, PAL.white);
  p.hline(4, 15, 9, withAlpha(PAL.slimeDark, 0.7));
}

function drawOctorok(p: Painter, dir: Dir, frame: number): void {
  const bob = frame % 2;
  const y = 4 + bob;
  p.ellipse(8, y + 5, 6, 5, PAL.bloodDark);
  p.ellipse(8, y + 4.5, 5, 4, PAL.blood);
  p.ellipse(6.5, y + 3, 2.5, 1.8, PAL.bloodLight);
  // Tentacle feet.
  for (let i = 0; i < 3; i++) {
    const fx = 4 + i * 4;
    p.rect(fx, 14 - bob, 2, 3, PAL.bloodDark);
    p.px(fx, 16 - bob, PAL.blood);
  }
  // Eyes / snout depend on facing.
  if (dir === 'up') {
    p.rect(5, y + 2, 2, 2, PAL.black);
    p.rect(9, y + 2, 2, 2, PAL.black);
  } else if (dir === 'down') {
    p.rect(5, y + 4, 2, 2, PAL.eyeWhite);
    p.rect(9, y + 4, 2, 2, PAL.eyeWhite);
    p.px(6, y + 5, PAL.pupil);
    p.px(10, y + 5, PAL.pupil);
    p.rect(7, y + 7, 2, 2, PAL.bloodDark);
  } else {
    p.rect(4, y + 4, 2, 2, PAL.eyeWhite);
    p.px(4, y + 5, PAL.pupil);
    p.rect(2, y + 6, 3, 2, PAL.bloodDark);
  }
}

function drawKeese(p: Painter, frame: number): void {
  const flap = [0, 2, 3, 2][frame];
  p.ellipse(8, 9, 3, 3.4, PAL.batDark);
  p.ellipse(8, 8.5, 2.2, 2.6, PAL.bat);
  p.px(6, 8, PAL.bloodLight);
  p.px(10, 8, PAL.bloodLight);
  // Wings sweep up and down with the flap phase.
  for (const side of [-1, 1]) {
    const x = 8 + side * 3;
    p.line(x, 8, x + side * 5, 8 - flap, PAL.batDark);
    p.line(x, 10, x + side * 5, 10 - flap + 1, PAL.batDark);
    p.line(x + side * 2, 9, x + side * 5, 9 - flap, PAL.batLight);
  }
  p.px(7, 12, PAL.batDark).px(9, 12, PAL.batDark);
}

function drawStalfos(p: Painter, dir: Dir, frame: number): void {
  const step = frame % 2 === 0 ? 0 : 1;
  // Legs and skirt of bone.
  p.rect(5, 15 + step, 2, 4 - step, PAL.plaster);
  p.rect(9, 16 - step, 2, 3 + step, PAL.plaster);
  p.rect(4, 10, 8, 6, PAL.steelDark);
  p.rect(4, 10, 8, 1, PAL.steel);
  p.rect(5, 14, 6, 1, shade(PAL.steelDark, 0.75));
  // Helm.
  p.rect(4, 3, 8, 7, PAL.steel);
  p.rect(4, 3, 8, 1, PAL.steelLight);
  p.rect(3, 5, 10, 2, PAL.steelDark);
  if (dir === 'down') {
    p.rect(5, 6, 2, 2, PAL.black);
    p.rect(9, 6, 2, 2, PAL.black);
    p.px(5, 6, PAL.fireLight);
    p.px(9, 6, PAL.fireLight);
  } else if (dir !== 'up') {
    p.rect(4, 6, 2, 2, PAL.black);
    p.px(4, 6, PAL.fireLight);
  }
  // Shield faces the direction of travel; that side is armoured.
  if (dir === 'left') p.rect(1, 9, 3, 7, PAL.bronze);
  else if (dir === 'right') p.rect(12, 9, 3, 7, PAL.bronze);
  else if (dir === 'down') p.rect(11, 10, 4, 6, PAL.bronze);
  else p.rect(1, 10, 4, 6, shade(PAL.bronze, 0.7));
}

function drawThornling(p: Painter, frame: number): void {
  const open = frame % 2 === 0;
  p.rect(7, 12, 2, 5, PAL.plantDark);
  p.line(6, 14, 3, 12, PAL.plantDark);
  p.line(10, 14, 13, 12, PAL.plantDark);
  p.ellipse(8, 9, 5, 5, PAL.plantDark);
  p.ellipse(8, 9, 4, 4, PAL.plant);
  if (open) {
    p.ellipse(8, 9, 2.6, 2.6, PAL.bloodDark);
    p.ellipse(8, 9, 1.4, 1.4, PAL.eyeWhite);
    p.px(8, 9, PAL.pupil);
    // Teeth.
    for (let i = 0; i < 4; i++) p.px(6 + i * 1.5, 7, PAL.white);
  } else {
    p.ellipse(8, 9, 3, 3, PAL.plantLight);
    p.hline(6, 9, 5, PAL.plantDark);
  }
}

// ---------------------------------------------------------------------------
// Boss: Thornmaw, Root of the Hollow
// ---------------------------------------------------------------------------

const BOSS_W = 48;
const BOSS_H = 48;

function drawThornmaw(p: Painter, frame: number, state: 'idle' | 'open' | 'hurt'): void {
  const pulse = frame % 2;
  const body = state === 'hurt' ? PAL.bloodDark : PAL.plantDark;
  const bodyLight = state === 'hurt' ? PAL.blood : PAL.plant;

  // Root tendrils spreading from the base.
  for (let i = 0; i < 6; i++) {
    const a = (i / 6) * Math.PI * 2 + frame * 0.1;
    const x = 24 + Math.cos(a) * 18;
    const y = 34 + Math.sin(a) * 10;
    p.line(24, 34, Math.round(x), Math.round(y), PAL.plantDark);
    p.px(Math.round(x), Math.round(y), PAL.woodDark);
  }

  // Bulb.
  p.ellipse(24, 26, 17, 16, body);
  p.ellipse(24, 25, 15, 14, bodyLight);
  p.ellipse(17, 18, 6, 5, PAL.plantLight);

  // Petals ringing the maw.
  for (let i = 0; i < 8; i++) {
    const a = (i / 8) * Math.PI * 2 + (pulse ? 0.15 : 0);
    const px1 = 24 + Math.cos(a) * 11;
    const py1 = 24 + Math.sin(a) * 10;
    const px2 = 24 + Math.cos(a) * (state === 'open' ? 18 : 15);
    const py2 = 24 + Math.sin(a) * (state === 'open' ? 17 : 14);
    p.line(Math.round(px1), Math.round(py1), Math.round(px2), Math.round(py2), PAL.bloodDark);
    p.px(Math.round(px2), Math.round(py2), PAL.white);
  }

  if (state === 'open' || state === 'hurt') {
    // Exposed eye — the only vulnerable moment.
    p.ellipse(24, 24, 9, 8, PAL.bloodDark);
    p.ellipse(24, 24, 7, 6, PAL.eyeWhite);
    p.ellipse(24, 24, 3.5, 4, PAL.pupil);
    p.ellipse(24, 24, 2, 2.4, state === 'hurt' ? PAL.fire : PAL.bloodLight);
    p.px(22, 22, PAL.white);
  } else {
    // Clamped shut.
    p.ellipse(24, 24, 9, 8, PAL.plantDark);
    p.hline(15, 24, 18, PAL.black);
    for (let i = 0; i < 7; i++) {
      p.px(16 + i * 3, 23, PAL.white);
      p.px(17 + i * 3, 25, PAL.white);
    }
  }
}

