/**
 * Procedural actor sprites. Every character is drawn from primitives into
 * per-direction animation frames at boot. Frame counts and cell sizes are
 * declared alongside each actor so the gameplay code can stay art-agnostic.
 */
import type { Dir } from '../engine/math';
import { PAL, shade, withAlpha } from './palette';
import { Painter, makeCanvas, type Canvas } from './paint';

export interface AnimSet {
  /** Cell width/height in pixels. */
  w: number;
  h: number;
  /** Pixel offset from the actor's feet-centre to the cell's top-left. */
  ox: number;
  oy: number;
  frames: Record<Dir, Canvas[]>;
}

export interface ActorArt {
  idle: AnimSet;
  walk: AnimSet;
  attack?: AnimSet;
  hurt?: AnimSet;
}

const DIRS: Dir[] = ['down', 'up', 'left', 'right'];

function flipX(src: Canvas): Canvas {
  const { canvas, ctx } = makeCanvas(src.width, src.height);
  ctx.translate(src.width, 0);
  ctx.scale(-1, 1);
  ctx.drawImage(src, 0, 0);
  return canvas;
}

/**
 * Builds an AnimSet by calling `draw` for each direction/frame. `right` is
 * generated by mirroring `left` unless the drawer handles it explicitly.
 */
function buildAnim(
  w: number,
  h: number,
  ox: number,
  oy: number,
  count: number,
  draw: (p: Painter, dir: Dir, frame: number) => void,
  mirrorRight = true,
): AnimSet {
  const frames = {} as Record<Dir, Canvas[]>;
  for (const dir of DIRS) {
    if (dir === 'right' && mirrorRight) continue;
    const list: Canvas[] = [];
    for (let f = 0; f < count; f++) {
      const p = new Painter(w, h);
      draw(p, dir, f);
      list.push(p.canvas);
    }
    frames[dir] = list;
  }
  if (mirrorRight) frames.right = frames.left.map(flipX);
  return { w, h, ox, oy, frames };
}

