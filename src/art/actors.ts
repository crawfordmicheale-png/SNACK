export interface ActorLibrary {
  hero: ActorArt & { shieldSet: AnimSet; spin: AnimSet };
  slime: ActorArt;
  octorok: ActorArt;
  keese: ActorArt;
  stalfos: ActorArt;
  thornling: ActorArt;
  boss: { idle: Canvas[]; open: Canvas[]; hurt: Canvas[]; w: number; h: number; ox: number; oy: number };
}

function omniAnim(w: number, h: number, ox: number, oy: number, count: number, draw: (p: Painter, f: number) => void): AnimSet {
  // Actors that look the same from every angle share one frame list.
  const list: Canvas[] = [];
  for (let f = 0; f < count; f++) {
    const p = new Painter(w, h);
    draw(p, f);
    list.push(p.canvas);
  }
  return { w, h, ox, oy, frames: { down: list, up: list, left: list, right: list } };
}

export function buildActorLibrary(): ActorLibrary {
  const bossFrames = (state: 'idle' | 'open' | 'hurt') => {
    const list: Canvas[] = [];
    for (let f = 0; f < 2; f++) {
      const p = new Painter(BOSS_W, BOSS_H);
      drawThornmaw(p, f, state);
      list.push(p.canvas);
    }
    return list;
  };

  return {
    hero: buildHeroArt(),
    slime: {
      idle: omniAnim(16, 16, -8, -14, 4, (p, f) => drawSlime(p, f)),
      walk: omniAnim(16, 16, -8, -14, 4, (p, f) => drawSlime(p, f)),
    },
    octorok: {
      idle: buildAnim(16, 18, -8, -16, 2, (p, dir, f) => drawOctorok(p, dir, f)),
      walk: buildAnim(16, 18, -8, -16, 2, (p, dir, f) => drawOctorok(p, dir, f)),
    },
    keese: {
      idle: omniAnim(16, 16, -8, -13, 4, (p, f) => drawKeese(p, f)),
      walk: omniAnim(16, 16, -8, -13, 4, (p, f) => drawKeese(p, f)),
    },
    stalfos: {
      idle: buildAnim(16, 20, -8, -18, 2, (p, dir, f) => drawStalfos(p, dir, f)),
      walk: buildAnim(16, 20, -8, -18, 2, (p, dir, f) => drawStalfos(p, dir, f)),
    },
    thornling: {
      idle: omniAnim(16, 18, -8, -16, 2, (p, f) => drawThornling(p, f)),
      walk: omniAnim(16, 18, -8, -16, 2, (p, f) => drawThornling(p, f)),
    },
    boss: {
      idle: bossFrames('idle'),
      open: bossFrames('open'),
      hurt: bossFrames('hurt'),
      w: BOSS_W,
      h: BOSS_H,
      ox: -24,
      oy: -42,
    },
  };
}
